const DICTS: Record<LangCode, Dict> = { fr, en, es, pt, de, ar, zh };

type Params = Record<string, string | number>;

/** Remplace les placeholders {name} d'une chaîne par leurs valeurs. */
function interpolate(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (m, name: string) => {
    const v = params[name];
    return v === undefined ? m : String(v);
  });
}

/** Locale Intl de la langue active (nombres, dates, devises — §9). */
export function localeFor(lang: LangCode): string {
  const map: Record<LangCode, string> = {
    fr: 'fr-FR', en: 'en-GB', es: 'es-ES', pt: 'pt-PT', de: 'de-DE', ar: 'ar-SA', zh: 'zh-CN',
  };
  return map[lang] ?? 'fr-FR';
}

/** Locale Intl de la langue persistée (hors hook). */
export function dashLocale(): string {
  let lang: LangCode = 'fr';
  try {
    const saved = safeStorage.get('local', 'nexus_lang') as LangCode | null;
    if (saved && saved in DICTS) lang = saved;
  } catch {
    // SSR / sandbox : fr par défaut.
  }
  return localeFor(lang);
}

/**
 * Mappe un code d'erreur backend vers une clé i18n lisible (§7).
 *
 * Les codes inconnus retombent sur la clé générique ; les pages peuvent
 * afficher le message brut du backend en dernier recours.
 */
export function dashError(code?: string | null, fallback?: string): string {
  const map: Record<string, string> = {
    INSUFFICIENT_FUNDS: 'errors.insufficientFunds',
    INSUFFICIENT_AVAILABLE_BALANCE: 'errors.insufficientFunds',
    INVALID_BENEFICIARY: 'errors.invalidBeneficiary',
    KYC_REQUIRED: 'errors.kycRequired',
    KYC_PENDING: 'errors.kycRequired',
    PAYMENT_METHOD_UNAVAILABLE: 'errors.paymentMethodUnavailable',
    ROUTE_UNAVAILABLE: 'errors.routeUnavailable',
    NO_AVAILABLE_PROVIDER: 'errors.noAvailableProvider',
    NO_PROVIDER: 'errors.routeUnavailable',
    PROVIDER_ERROR: 'errors.providerError',
    TRANSFER_FAILED: 'errors.transferFailed',
    FX_UNAVAILABLE: 'errors.fxUnavailable',
    FX_RATE_NOT_AVAILABLE: 'errors.fxUnavailable',
    QUOTE_EXPIRED: 'errors.quoteExpired',
    QUOTE_ALREADY_EXECUTED: 'errors.quoteAlreadyExecuted',
    IDEMPOTENCY_ERROR: 'errors.idempotency',
    IDEMPOTENCY_IN_PROGRESS: 'errors.idempotency',
  };
  const key = code ? map[code] : undefined;
  if (key) return dashTranslate(key);
  return fallback ?? dashTranslate('errors.generic');
}

/** Hook : fonction de traduction des dashboards pour la langue active. */
export function useDashT(): (key: string, params?: Params) => string {
  const { lang } = useI18n();
  const dict = DICTS[(lang as LangCode) in DICTS ? (lang as LangCode) : 'fr'];
  return (key: string, params?: Params) => interpolate(dict[key] ?? fr[key] ?? key, params);
}

/** Traduction hors hook (statuts, utilitaires) — lit la langue persistée. */
export function dashTranslate(key: string, params?: Params): string {
  let lang: LangCode = 'fr';
  try {
    const saved = safeStorage.get('local', 'nexus_lang') as LangCode | null;
    if (saved && saved in DICTS) lang = saved;
  } catch {
    // SSR / sandbox : fr par défaut.
  }
  return interpolate(DICTS[lang][key] ?? fr[key] ?? key, params);

}


