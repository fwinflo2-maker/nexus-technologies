/** Traduction du Control Center. Repli : langue courante → français → clé. */
export function useCtrlT(): (key: string) => string {
  const { lang } = useI18n();
  const dict = DICTS[(lang as LangCode) in DICTS ? (lang as LangCode) : 'fr'];
  return (key: string) => dict[key] ?? fr[key] ?? key;
}

